const DICTS: Record<Lang, Dict> = { en, hi, kn, ta, ml };

let current: Lang = 'en';
const listeners = new Set<() => void>();

export function setLanguage(l: Lang): void {
  if (l === current) return;
  current = l;
  document.documentElement.lang = l;
  applyLanguage(document.body);
  listeners.forEach((fn) => fn());
}

export function getLanguage(): Lang {
  return current;
}

/** Subscribe to language changes (dynamic UIs re-render themselves). */
export function onLanguage(fn: () => void): () => void {
  listeners.add(fn);
  return () => listeners.delete(fn);
}

/** Translate `key`, substituting `{name}` placeholders. Falls back to English, then the key. */
export function t(key: string, vars: Record<string, string | number> = {}): string {
  let s = DICTS[current][key] ?? en[key] ?? key;
  for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
  return s;
}

/** Refresh every `data-i18n` / `data-i18n-html` node under `root`. */
export function applyLanguage(root: ParentNode = document.body): void {
  root.querySelectorAll<HTMLElement>('[data-i18n]').forEach((el) => {
    el.textContent = t(el.dataset.i18n!);
  });
  root.querySelectorAll<HTMLElement>('[data-i18n-html]').forEach((el) => {
    el.innerHTML = t(el.dataset.i18nHtml!);
  });
  root.querySelectorAll<HTMLInputElement>('[data-i18n-placeholder]').forEach((el) => {
    el.placeholder = t(el.dataset.i18nPlaceholder!);
  });
}
